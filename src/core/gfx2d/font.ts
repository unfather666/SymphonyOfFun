export const GLYPH_W = 5;
export const GLYPH_H = 7;
export const ADVANCE = 6;
export const LINE_H = 8;

/** Glyph as a 7-entry array of 5-bit rows (bit 4 = leftmost pixel). */
export function glyphRows(ch: string): readonly number[] {
  const key = G[ch] !== undefined ? ch : G[ch.toUpperCase()] !== undefined ? ch.toUpperCase() : '?';
  return cache.get(key) ?? build(key);
}

const cache = new Map<string, number[]>();
function build(key: string): number[] {
  const rows = G[key]!.split('|').map((r) => {
    let v = 0;
    for (let i = 0; i < GLYPH_W; i++) v = (v << 1) | (r[i] === '#' ? 1 : 0);
    return v;
  });
  cache.set(key, rows);
  return rows;
}

export const GLYPHS: readonly string[] = Object.keys(G);
export const GLYPH_DATA: Readonly<Record<string, string>> = G;

export function textWidth(text: string, scale = 1): number {
  let max = 0;
  for (const line of text.split('\n')) max = Math.max(max, line.length);
  return max === 0 ? 0 : (max * ADVANCE - 1) * scale;
}
